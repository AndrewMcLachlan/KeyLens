using System.ComponentModel;
using KeyLens.Connections;
using KeyLens.Security;

namespace KeyLens.Modules.Connections.Commands;

[DisplayName("CreateConnection")]
public sealed record Create(string Name, Entities.ConnectionType Type, object Config, string? Secret, bool Enabled = true) : ICommand<Models.Connection>;

internal class CreateHandler(
    Entities.IConnectionRepository repository,
    IConnectionSecretStore secretStore,
    IUserDataProvider userDataProvider,
    IUnitOfWork unitOfWork) : ICommandHandler<Create, Models.Connection>
{
    public async ValueTask<Models.Connection> Handle(Create command, CancellationToken cancellationToken)
    {
        var config = ConnectionCommandValidation.Validate(command.Type, command.Config, command.Secret);

        /* The id names this connection's secret in the vault, so it must exist before the row is
           written rather than being generated by the database on save. */
        var connection = new Entities.Connection(Guid.CreateVersion7())
        {
            OwnerId = userDataProvider.CurrentUserId,
            Name = command.Name,
            Type = command.Type,
            Enabled = command.Enabled,
            Config = config,
            Created = DateTimeOffset.UtcNow,
        };

        repository.Add(connection);

        if (!String.IsNullOrWhiteSpace(command.Secret))
        {
            connection.SecretName = await secretStore.SetAsync(connection.Id, command.Secret, cancellationToken: cancellationToken);
            connection.SecretUpdated = DateTimeOffset.UtcNow;
        }

        await unitOfWork.SaveChangesAsync(cancellationToken);

        return connection.ToModel();
    }
}
